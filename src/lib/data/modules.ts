/**
 * Module descriptor registry. Each entry drives a complete, professional module
 * workspace (KPIs, record table, workflow states, configuration) for an SRS
 * route. Data is representational only (SRS §9: no client figures seeded).
 *
 * Bespoke screens (POS, invoices, rates, COA, karigar, customers, employees,
 * RBAC) are implemented as explicit routes and take precedence over this
 * generic workspace; everything else renders from a descriptor here.
 */

export interface ModuleColumn {
  key: string;
  header: string;
  align?: "left" | "right" | "center";
  mono?: boolean;
  kind?: "text" | "status" | "money" | "badge" | "muted";
}

export interface ModuleKpi {
  label: string;
  value: string;
  delta?: string;
  direction?: "up" | "down" | "flat";
  accent?: "primary" | "accent" | "success" | "warning" | "danger" | "info";
}

export interface ModuleSpec {
  /** SRS requirement cluster realized by this screen */
  srs?: string;
  summary: string;
  kpis: ModuleKpi[];
  recordLabel: string;
  columns: ModuleColumn[];
  rows: Record<string, any>[];
  /** lifecycle states (SRS §10 state machine) shown as a pipeline */
  states?: string[];
  /** configuration / capability bullets (FR catalog) */
  capabilities?: string[];
}

